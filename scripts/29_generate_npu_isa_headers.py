NOTICE = "Generated by scripts/29_generate_npu_isa_headers.py; do not edit."


def enum_sv(prefix: str, enum_type: type, width: int) -> list[str]:
    values = list(enum_type)
    digits = width // 4
    return [
        f"    {prefix}_{item.name} = {width}'h{int(item):0{digits}x}"
        + ("," if index + 1 < len(values) else "")
        for index, item in enumerate(values)
    ]


def enum_c(prefix: str, enum_type: type) -> list[str]:
    return [f"#define {prefix}_{item.name} 0x{int(item):02x}u"
            for item in enum_type]


